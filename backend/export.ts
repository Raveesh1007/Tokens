import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { abiOf, root } from "./lib";

const dir = join(root, "contracts/deployments");
const wanted = process.argv.slice(2);
const files = readdirSync(dir).filter((f) => f.endsWith(".json") && (!wanted.length || wanted.includes(f.slice(0, -5))));
if (!files.length) throw new Error(`no deployments in ${dir} for ${wanted.join(",") || "any chain"}`);

const deployments: Record<string, unknown> = {};
for (const f of files) deployments[f.slice(0, -5)] = JSON.parse(readFileSync(join(dir, f), "utf8"));

const abi = (name: string) => `[\n${abiOf(name).map((i) => `  ${JSON.stringify(i)}`).join(",\n")},\n] as const`;

const out = `// generated by backend/export.ts, do not edit
export const deployments = ${JSON.stringify(deployments, null, 2)} as const;

export const vaultAbi = ${abi("Vault")};

export const tokenAbi = ${abi("Token")};
`;

const target = process.env.OUT ?? join(root, "web/src/lib/contracts.ts");
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, out);
console.log(`wrote ${target} for chains ${Object.keys(deployments).join(", ")}`);
